// Turns the raw campaign stills in /assets-src into responsive WebP files in
// /public/images and writes a typed manifest to src/lib/images.generated.ts.
//
//   npm run images
//
// Every source image is an original still generated for this concept
// (see CREDITS.md for prompts, model and provenance).
import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const SRC = path.join(ROOT, "assets-src");
const OUT = path.join(ROOT, "public", "images");
const MANIFEST = path.join(ROOT, "src", "lib", "images.generated.ts");

/** slug, responsive widths, optional crop (fractions of the source) */
const CONFIG = {
  "01-hero-totality": { slug: "hero", widths: [640, 1100, 1600, 2048] },
  "02-annulus": { slug: "annulus", widths: [480, 880] },
  "03-corona": { slug: "corona", widths: [480, 880] },
  "04-bailys-beads": { slug: "bailys-beads", widths: [480, 880] },
  "05-diamond-ring": { slug: "diamond-ring", widths: [480, 880] },
  "06-penumbra": { slug: "penumbra", widths: [480, 880] },
  "07-umbra": { slug: "umbra", widths: [480, 880] },
  "08-second-contact": { slug: "second-contact", widths: [480, 880] },
  // keep the composition on the ruff and the face
  "09-chromosphere": { slug: "chromosphere", widths: [480, 880], crop: { top: 0, height: 0.8 } },
  "10-anatomy": { slug: "anatomy", widths: [560, 912] },
  "11-contact-hall": { slug: "contact-hall", widths: [960, 1600, 2400] },
  "12-contact-hands": { slug: "contact-hands", widths: [960, 1360] },
  "13-totality": { slug: "totality", widths: [960, 1600, 2400] },
  "14-contact-corridor": { slug: "contact-corridor", widths: [960, 1600, 2400] },
  "15-atelier-hands": { slug: "atelier-hands", widths: [480, 912] },
  "16-material-macro": { slug: "material-macro", widths: [640, 1360] },
  "17-closing-crescent": { slug: "closing", widths: [960, 1600, 2400] },
};

await mkdir(OUT, { recursive: true });
const files = (await readdir(SRC)).filter((f) => f.endsWith(".png")).sort();
const manifest = {};

for (const file of files) {
  const key = file.replace(/\.png$/, "");
  const cfg = CONFIG[key];
  if (!cfg) {
    console.warn(`skip ${file} (no config)`);
    continue;
  }
  let base = sharp(path.join(SRC, file));
  const meta = await base.metadata();
  let w = meta.width;
  let h = meta.height;
  if (cfg.crop) {
    const top = Math.round(h * cfg.crop.top);
    const height = Math.round(h * cfg.crop.height);
    base = sharp(await base.extract({ left: 0, top, width: w, height }).toBuffer());
    h = height;
  }
  const buffer = await base.toBuffer();
  const sources = [];
  for (const target of cfg.widths) {
    const width = Math.min(target, w);
    const name = `${cfg.slug}-${width}.webp`;
    await sharp(buffer)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 80, effort: 5 })
      .toFile(path.join(OUT, name));
    if (!sources.find((s) => s.width === width)) sources.push({ width, src: `/images/${name}` });
  }
  // 24px blurred placeholder, inlined as a data URI
  const tiny = await sharp(buffer).resize({ width: 24 }).blur(1.2).webp({ quality: 40 }).toBuffer();
  manifest[cfg.slug] = {
    width: w,
    height: h,
    src: sources[sources.length - 1].src,
    srcSet: sources.map((s) => `${s.src} ${s.width}w`).join(", "),
    placeholder: `data:image/webp;base64,${tiny.toString("base64")}`,
  };
  console.log(`${cfg.slug.padEnd(18)} ${w}x${h} → ${sources.map((s) => s.width).join(", ")}`);
}

// Open Graph / social card, cropped from the Totality frame
const og = path.join(SRC, "13-totality.png");
await sharp(og)
  .resize({ width: 1200, height: 630, fit: "cover", position: "centre" })
  .jpeg({ quality: 84, mozjpeg: true })
  .toFile(path.join(ROOT, "public", "og.jpg"));

const body = `// AUTO-GENERATED by scripts/process-images.mjs — do not edit by hand.
export type ImageAsset = {
  width: number;
  height: number;
  src: string;
  srcSet: string;
  placeholder: string;
};

export const IMAGES = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageAsset>;

export type ImageSlug = keyof typeof IMAGES;
`;
await writeFile(MANIFEST, body);
console.log(`\nmanifest → ${path.relative(ROOT, MANIFEST)}`);
