// Extracts the handful of Solar icons the site uses (via Iconify's
// @iconify-json/solar set, MIT / CC BY 4.0 — Solar by 480 Design) into a tiny
// local module, so no icon font or runtime API call is needed.
//
//   npm run icons
import { createRequire } from "node:module";
import { writeFile } from "node:fs/promises";
import path from "node:path";

const require = createRequire(import.meta.url);
const set = require("@iconify-json/solar/icons.json");
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");

const NAMES = {
  bag: "bag-4-linear",
  close: "close-linear",
  arrowRight: "arrow-right-linear",
  arrowLeft: "arrow-left-linear",
  arrowUpRight: "arrow-right-up-linear",
  arrowUp: "arrow-up-linear",
  chevronDown: "alt-arrow-down-linear",
  plus: "add-circle-linear",
  minus: "minus-circle-linear",
  menu: "hamburger-menu-linear",
  clock: "clock-circle-linear",
  pin: "map-point-linear",
  letter: "letter-linear",
  check: "check-circle-linear",
  danger: "danger-circle-linear",
  trash: "trash-bin-minimalistic-linear",
  video: "videocamera-record-linear",
  calendar: "calendar-linear",
  drag: "round-transfer-horizontal-linear",
};

const out = {};
for (const [key, name] of Object.entries(NAMES)) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Solar icon not found: ${name}`);
  out[key] = { body: icon.body, width: icon.width ?? set.width ?? 24, height: icon.height ?? set.height ?? 24 };
}

const body = `// AUTO-GENERATED by scripts/extract-icons.mjs from @iconify-json/solar.
// Solar icon set by 480 Design — https://icon-sets.iconify.design/solar/ (CC BY 4.0)
export const ICONS = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof ICONS;
`;
await writeFile(path.join(ROOT, "src", "lib", "icons.generated.ts"), body);
console.log(`wrote ${Object.keys(out).length} Solar icons`);
